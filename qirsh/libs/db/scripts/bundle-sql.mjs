// Bundles supabase/migrations and supabase/local into a TypeScript module, so the browser
// demo, the tests and `supabase db push` all run the very same SQL files.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../supabase/", import.meta.url));
const read = (dir) =>
  readdirSync(join(root, dir))
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((f) => ({ name: `${dir}/${f}`, sql: readFileSync(join(root, dir, f), "utf8") }));

const out = `// Generated by scripts/bundle-sql.mjs from supabase/. Do not edit.
export const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(read("migrations"), null, 1)};
export const LOCAL: { name: string; sql: string }[] = ${JSON.stringify(read("local"), null, 1)};
`;
writeFileSync(new URL("../src/sql.generated.ts", import.meta.url), out);
